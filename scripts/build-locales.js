"use strict";
const fs = require("node:fs"), path = require("node:path");
const root = path.resolve(__dirname, "..");
const source = JSON.parse(fs.readFileSync(path.join(root, "locales/ui.json"), "utf8"));
const output = "/* Generated by scripts/build-locales.js from locales/ui.json. */\n(() => { const catalogs = " + JSON.stringify(source) + "; window.KaiLocaleCatalogs ||= {}; for (const [language, entries] of Object.entries(catalogs)) Object.assign(window.KaiLocaleCatalogs[language] ||= {}, entries); })();\n";
const targets = ["plugin/locales/ui.js"];
if (fs.existsSync(path.join(root,"plugin/service/ui/mascot.html"))) targets.push("plugin/service/ui/locales/ui.js");
for (const target of targets) {
  const filename = path.join(root, target);
  if (process.argv.includes("--check")) { if (!fs.existsSync(filename) || fs.readFileSync(filename,"utf8") !== output) throw Error("Rebuild locale catalogs: " + target); }
  else { fs.mkdirSync(path.dirname(filename), {recursive:true}); fs.writeFileSync(filename, output); }
}
